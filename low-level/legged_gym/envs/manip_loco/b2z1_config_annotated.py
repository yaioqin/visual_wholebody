from legged_gym.envs.base.legged_robot_config import LeggedRobotCfg, LeggedRobotCfgPPO
import numpy as np


# 环境配置：在通用 LeggedRobotCfg 基础上定义 B2 底盘 + Z1 机械臂任务。
class B2Z1RoughCfg(LeggedRobotCfg):
    # 末端执行器（end effector, EE）目标生成及安全约束。
    class goal_ee:
        # 含义：EE 命令维数，当前为球坐标的距离、俯仰角、偏航角。
        # 作用：决定目标采样张量的最后一维；模型联动：【必须联动】机械臂任务接口变化时修改。
        num_commands = 3

        # 含义：一次 EE 目标插值运动的时间范围 [最小, 最大]，单位 s。
        # 作用：越短动作越激进；模型联动：【建议复核】随 Z1 速度/负载能力复核。
        traj_time = [1, 3]

        # 含义：到达目标后保持该目标的时间范围，单位 s。
        # 作用：控制目标更新频率和静态跟踪占比；模型联动：【任务决定】。
        hold_time = [0.5, 2]

        # 含义：以球坐标中心为原点的禁入长方体上界 [x, y, z]，单位 m。
        # 作用：目标轨迹进入该盒体会被拒绝，避免机械臂目标穿过机身；模型联动：【必须联动】随机身外形/安装位姿修改。
        collision_upper_limits = [0.1, 0.2, -0.05]

        # 含义：禁入长方体下界 [x, y, z]，单位 m。
        # 作用：与上界共同包围 B2 机身及附近危险区域；模型联动：【必须联动】随 B2 尺寸、Z1 安装高度及球心位置修改。
        collision_lower_limits = [-0.8, -0.2, -0.84851]

        # 含义：EE 目标相对球心允许的最低 z，单位 m。
        # 作用：插值轨迹低于该高度会被判定无效，防止目标进入地面；模型联动：【必须联动】随球心离地高度修改。
        underground_limit = -0.84851

        # 含义：从起点到终点做碰撞检查的离散采样数。
        # 作用：越大越不易漏检、计算越多；模型联动：【通常不联动】，长轨迹或狭窄安全区可增大。
        num_collision_check_samples = 10

        # 含义：EE 位置命令表达方式，可取 'sphere' 或 'cart'。
        # 作用：决定目标采样和误差计算坐标系；模型联动：【任务决定】，改后需同步观测/奖励接口。
        command_mode = 'sphere'

        # 含义：由目标位置方向推导默认末端俯仰角时附加的偏置，单位 rad。
        # 作用：default_pitch = -pos_p + arm_induced_pitch；模型联动：【必须联动】随末端坐标系、安装姿态和工具朝向修改。
        arm_induced_pitch = 0.38

        # EE 球坐标系中心；x/y 随机身 yaw 旋转，z 使用相对地形的不变量。
        class sphere_center:
            # 含义：球心相对 base_link 的前向 x 偏移，单位 m。
            # 作用：使目标空间以机械臂安装区域为中心；模型联动：【必须联动】应与 B2→Z1 安装变换一致。
            x_offset = 0.34218

            # 含义：球心相对 base_link 的横向 y 偏移，单位 m。
            # 作用：描述机械臂是否偏心安装；模型联动：【必须联动】随安装位置修改。
            y_offset = 0

            # 含义：球心相对地形原点的固定 z 偏移，单位 m。
            # 作用：目标球心不随 base_link 上下振动；模型联动：【必须联动】随机器人标称高度、机械臂安装高度修改。
            z_invariant_offset = 0.84851

        # EE 球坐标采样范围。
        class ranges:
            # 含义：episode 初始化时 EE 插值起点 [距离 l, 俯仰 p, 偏航 y]。
            # 作用：规定复位后的初始目标；模型联动：【建议复核】须位于 Z1 可达空间且无碰撞。
            init_pos_start = [0.5, np.pi / 8, 0]

            # 含义：episode 初始化时 EE 插值终点 [l, p, y]。
            # 作用：机器人启动后首先移动到此目标；模型联动：【建议复核】须验证可达性和自碰撞。
            init_pos_end = [0.7, 0, 0]

            # 含义：随机球坐标半径范围，单位 m。
            # 作用：决定目标距离；模型联动：【必须联动】随 Z1 臂长、工具长度和安装位置修改。
            pos_l = [0.4, 0.95]

            # 含义：随机球坐标俯仰角范围，单位 rad。
            # 作用：决定目标上下方向；模型联动：【建议复核】随可达空间、地面及机身碰撞范围修改。
            pos_p = [-1 * np.pi / 2.5, 1 * np.pi / 3]

            # 含义：随机球坐标偏航角范围，单位 rad。
            # 作用：决定目标左右覆盖范围；模型联动：【建议复核】随安装位置、关节限位和自碰撞修改。
            pos_y = [-1.2, 1.2]

            # 含义：末端目标 roll 相对默认朝向的随机增量范围，单位 rad。
            # 作用：增加姿态跟踪多样性；模型联动：【建议复核】随腕部限位和工具需求修改。
            delta_orn_r = [-0.5, 0.5]

            # 含义：末端目标 pitch 随机增量范围，单位 rad。
            # 作用：增加俯仰姿态多样性；模型联动：【建议复核】随腕部限位和工具需求修改。
            delta_orn_p = [-0.5, 0.5]

            # 含义：末端目标 yaw 随机增量范围，单位 rad。
            # 作用：增加偏航姿态多样性；模型联动：【建议复核】随腕部限位和工具需求修改。
            delta_orn_y = [-0.5, 0.5]

            # 含义：历史遗留的最终 EE 跟踪奖励目标值。
            # 作用：当前仓库代码未读取；模型联动：【当前未生效】，启用对应课程代码后再按任务调整。
            final_tracking_ee_reward = 0.55

        # 含义：球坐标三个误差分量的逐维权重 [l, p, y]。
        # 作用：乘到 EE 球坐标绝对误差上；模型联动：【任务决定】，半径/角度量纲差异较大时建议归一化。
        sphere_error_scale = [1, 1, 1]

        # 含义：末端姿态 roll/pitch/yaw 误差的逐维权重。
        # 作用：乘到姿态角误差上；模型联动：【任务决定】，工具对某一轴更敏感时修改。
        orn_error_scale = [1, 1, 1]

    # 观测噪声，用于提升 sim-to-real 鲁棒性。
    class noise:
        # 含义：是否向观测加入均匀噪声。
        # 作用：False 时下列噪声尺度均不生效；模型联动：【任务决定】，实机部署通常建议启用并按传感器标定。
        add_noise = False

        # 含义：所有 noise_scales 的总倍率。
        # 作用：统一放大/缩小噪声；模型联动：【任务决定】，按实机传感器噪声调整。
        noise_level = 1.0

        class noise_scales:
            # 含义：关节位置观测噪声幅度，进入观测前还乘 obs_scales.dof_pos。
            # 作用：模拟编码器位置误差；模型联动：【建议复核】随 B2 编码器精度修改；当前 Z1 位置噪声代码设为 0。
            dof_pos = 0.01

            # 含义：关节速度观测噪声幅度，进入观测前还乘 obs_scales.dof_vel。
            # 作用：模拟差分速度/编码器速度误差；模型联动：【建议复核】随传感器精度修改；当前 Z1 速度噪声代码设为 0。
            dof_vel = 1.5

            # 含义：机身线速度噪声幅度。
            # 作用：通用基类预留；当前 ManipLoco 观测不包含 base_lin_vel，故【当前未生效】。
            lin_vel = 0.1

            # 含义：机身角速度噪声幅度。
            # 作用：模拟 IMU 陀螺仪噪声；模型联动：【建议复核】按实机 IMU 指标修改。
            ang_vel = 0.2

            # 含义：投影重力/姿态观测噪声幅度。
            # 作用：通用基类预留；当前 body orientation 明确不加噪声，故【当前未生效】。
            gravity = 0.05

            # 含义：地形高度采样噪声幅度。
            # 作用：模拟高度感知误差；当前 proprio 中没有拼入高度点，需结合噪声索引代码检查，模型联动：【当前未生效/需谨慎】。
            height_measurements = 0.1

    # B2 速度命令配置。
    class commands:
        # 含义：是否启用命令课程学习。
        # 作用：允许训练过程中逐步扩大命令难度；当前 ManipLoco 未实现通用命令课程更新，模型联动：【当前未生效】。
        curriculum = True

        # 含义：速度命令维数，依次为 vx、vy、yaw 角速度。
        # 作用：决定命令张量维度；模型联动：【必须联动】控制/观测接口变化时修改。
        num_commands = 3

        # 含义：重新采样速度命令的周期，单位 s。
        # 作用：越短命令切换越频繁；模型联动：【任务决定】，也应考虑 B2 动态响应速度。
        resampling_time = 3.0

        # 含义：历史遗留的前向速度课程区间。
        # 作用：当前仓库没有读取该字段；模型联动：【当前未生效】。
        lin_vel_x_schedule = [0, 0.5]

        # 含义：历史遗留的 yaw 命令课程区间。
        # 作用：当前仓库没有读取该字段；模型联动：【当前未生效】。
        ang_vel_yaw_schedule = [0, 1]

        # 含义：历史遗留的 yaw 跟踪课程区间。
        # 作用：当前仓库没有读取该字段；模型联动：【当前未生效】。
        tracking_ang_vel_yaw_schedule = [0, 1]

        # 含义：判断“有效旋转命令”的 yaw 角速度阈值，单位 rad/s。
        # 作用：用于横向速度惩罚等逻辑的掩码；模型联动：【任务决定】。
        ang_vel_yaw_clip = 0.5

        # 含义：判断静止/行走命令的前向速度阈值，单位 m/s。
        # 作用：影响 walking mask、零命令奖励和命令清零；模型联动：【任务决定】。
        lin_vel_x_clip = 0.2

        class ranges:
            # 含义：前向速度采样范围 [min, max]，单位 m/s。
            # 作用：定义 B2 训练速度包络；模型联动：【建议复核】应符合 B2 稳定速度和实机安全范围。
            lin_vel_x = [-0.8, 0.8]

            # 含义：yaw 角速度采样范围 [min, max]，单位 rad/s。
            # 作用：定义转向训练包络；模型联动：【建议复核】应符合 B2 转向能力和实机安全范围。
            ang_vel_yaw = [-1.0, 1.0]

    # 输入/输出数值归一化与裁剪。
    class normalization:
        class obs_scales:
            # 含义：机身线速度观测缩放。
            # 作用：通用字段；当前 ManipLoco proprio 不含 base_lin_vel，故【当前未生效】。
            lin_vel = 1.0

            # 含义：机身角速度观测缩放。
            # 作用：改善网络输入量级；模型联动：【通常不联动】，改观测定义或量级时调整。
            ang_vel = 1.0

            # 含义：关节位置相对默认角的观测缩放。
            # 作用：改善网络输入量级；模型联动：【建议复核】关节范围变化较大时调整。
            dof_pos = 1.0

            # 含义：关节速度观测缩放。
            # 作用：把 rad/s 压到适合网络的量级；模型联动：【建议复核】随关节速度上限修改。
            dof_vel = 0.05

            # 含义：地形高度观测缩放。
            # 作用：通用字段；当前观测未明确拼入高度点，故【当前未生效/需与观测代码同步】。
            height_measurements = 5.0

        # 含义：网络观测逐元素绝对值裁剪上限。
        # 作用：防止异常状态产生极端输入；模型联动：【通常不联动】。
        clip_observations = 100.0

        # 含义：策略动作逐元素绝对值裁剪上限。
        # 作用：当前值 100 基本不约束常见高斯动作，实际幅度主要由 action_scale 和关节力矩限位控制；模型联动：【建议复核】。
        clip_actions = 100.0

    # 并行环境、动作和观测张量结构。
    class env:
        # 含义：并行仿真环境数量。
        # 作用：影响吞吐、显存和每次 PPO 更新样本量；模型联动：【通常不联动】，按 GPU 资源调整。
        num_envs = 6144

        # 含义：策略动作维数：12 个 B2 腿关节 + 6 个 Z1 臂关节。
        # 作用：决定策略输出形状；当前 step 会把后 6 维清零并由 IK 控臂；模型联动：【必须联动】随可控自由度数量修改。
        num_actions = 12 + 6

        # 含义：计算力矩的执行器数量：12 腿 + 6 臂，不含夹爪。
        # 作用：决定力矩、增益、motor_strength 张量宽度；模型联动：【必须联动】随执行器数量和 DOF 排列修改。
        num_torques = 12 + 6

        # 含义：动作延迟缓冲参数；-1 表示不使用缓冲。
        # 作用：当前前 10000*24 步取最新动作，之后固定取前一帧动作，数值 3 主要决定缓冲区长度；模型联动：【任务决定】，实机部署应按通信/执行延迟校准。
        action_delay = 3

        # 含义：URDF 中夹爪 DOF 数量。
        # 作用：从状态和动作控制中切除夹爪，并确定臂关节切片；模型联动：【必须联动】随夹爪结构修改。
        num_gripper_joints = 1

        # 含义：单帧 proprio 维数 = 姿态2 + 角速度3 + 关节位置18 + 关节速度18 + 腿动作12 + 足接触4 + 速度命令3 + EE位置3 + EE姿态3 = 66。
        # 作用：分配历史观测并校验网络输入；模型联动：【必须联动】任何观测项或 DOF 数变化都要同步修改。
        num_proprio = 2 + 3 + 18 + 18 + 12 + 4 + 3 + 3 + 3

        # 含义：域随机化特权参数维数 = 质量/COM/夹爪质量5 + 摩擦1 + 腿电机强度12 = 18。
        # 作用：拼入当前 obs 供 privileged encoder 使用；模型联动：【必须联动】特权信息组成或腿执行器数量变化时修改。
        num_priv = 5 + 1 + 12

        # 含义：保存的过去 proprio 帧数。
        # 作用：策略可从历史估计速度、延迟和隐含动力学；模型联动：【通常不联动】，增大会增加网络输入和显存。
        history_len = 10

        # 含义：总观测维数 = 当前帧及 10 帧历史 + 当前特权参数 = 66*11+18=744。
        # 作用：决定 actor/critic 输入宽度；模型联动：【必须联动】必须与实际拼接完全一致。
        num_observations = num_proprio * (history_len + 1) + num_priv

        # 含义：独立 privileged_obs_buf 的维数；None 表示不单独返回 critic 观测。
        # 作用：当前特权参数直接拼入 obs_buf；模型联动：【通常不联动】，改非对称 actor-critic 接口时同步修改。
        num_privileged_obs = None

        # 含义：是否把 episode 超时掩码传给算法。
        # 作用：算法可对 timeout 正确 bootstrap；模型联动：【通常不联动】。
        send_timeouts = True

        # 含义：单个 episode 最长时间，单位 s。
        # 作用：决定 reset 周期和训练轨迹长度；模型联动：【任务决定】。
        episode_length_s = 10

        # 含义：是否把 Isaac Gym 的 DOF/足端顺序重排为策略约定顺序。
        # 作用：当前映射腿顺序为 FR、FL、RR、RL；模型联动：【必须联动】URDF DOF 顺序或策略顺序变化时修改映射代码。
        reorder_dofs = True

        # 含义：是否由 teleop.py/外部设备提供命令。
        # 作用：启用时停止自动重采样部分命令；模型联动：【任务决定】。
        teleop_mode = False

        # 含义：是否为每个环境创建录制相机。
        # 作用：便于保存视频，但显著增加资源消耗；模型联动：【通常不联动】。
        record_video = False

        # 含义：是否进入待机模式。
        # 作用：待机时在观测计算阶段把速度命令清零；模型联动：【任务决定】。
        stand_by = False

        # 含义：是否把步态相位和四足时钟共 5 维加入观测。
        # 作用：启用显式步态控制及接触整形奖励；模型联动：【任务决定】，开启后代码自动把 num_proprio 增加 5。
        observe_gait_commands = False

        # 含义：步态相位频率，单位 Hz。
